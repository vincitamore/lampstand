"""Shared fixtures for the Hermes adapter tests: temp houses, an isolated environment and a recording ctx.

Every path a test touches is under a temporary directory; state and config roots point there and HOUSE_ROOT is
removed, so nothing reads or writes the machine's real lampstand locations.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from hosts.hermes.projection import input_hash, input_paths

REPO = Path(__file__).resolve().parents[2]
NODE = shutil.which("node")
BIN = REPO / "core" / "bin" / "lampstand.js"
HOUSE_ID = "0b9a1c2e-4f5d-4e6a-8b7c-9d0e1f2a3b4c"
PRINCIPLE = (
    '---\norigin: own\nadopted: "2026-01-01"\nadopted-hash: "' + "a" * 64 + '"\noccasion: a test house\n---\n'
    "### A : Care\n\n*Look before acting.*\n\n- **eyes**: read first\n\n*Vice:* Haste.\n"
)


def house_toml(gate: str = "remind") -> str:
    return (
        f'[house]\nschema = 1\nid = "{HOUSE_ID}"\nname = "test-house"\n\n'
        '[purpose]\ntext = "Keep the test honest."\n\n'
        '[charter]\nask_first = ["deleting files"]\n\n'
        f'[gate]\nmode = "{gate}"\n'
    )


def vectors(kind: str) -> list[dict]:
    directory = REPO / "schema" / "conformance" / kind
    out: list[dict] = []
    for path in sorted(directory.glob("*.json")):
        out.extend(json.loads(path.read_text(encoding="utf-8"))["vectors"])
    return out


def plant(root: Path, files: dict[str, str]) -> None:
    for rel, text in files.items():
        target = root.joinpath(*rel.split("/"))
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(text.encode("utf-8"))


def region(kernel_file: Path) -> str:
    """An AGENTS.md region the way the compiler lays it out: the header, the kernel marker and K."""
    return f"<!-- house:begin -->\n{kernel_file.read_text(encoding='utf-8').rstrip()}\n<!-- house:end -->\n"


class TempTestCase(unittest.TestCase):
    """A real-path temp directory and an environment confined to it for the length of each test."""

    def setUp(self) -> None:
        self.tmp = Path(os.path.realpath(tempfile.mkdtemp(prefix="lampstand-u6-")))
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        roots = {"LAMPSTAND_STATE_ROOT": "state-root", "LAMPSTAND_CONFIG_ROOT": "config-root"}
        env = mock.patch.dict(os.environ, {key: str(self.tmp / name) for key, name in roots.items()})
        env.start()
        self.addCleanup(env.stop)
        os.environ.pop("HOUSE_ROOT", None)

    def make_house(self, rel: str = "house", gate: str = "remind", generated: str | None = "fixture") -> Path:
        """A house with one principle. `generated` is "node" for a real compile, "fixture" for projections written
        here in the compiler's layout (so tests of the adapter's own decisions do not hang on the CLI), or None."""
        root = self.tmp.joinpath(*rel.split("/"))
        plant(root, {"house.toml": house_toml(gate), "principles/own.md": PRINCIPLE, "tasks/.keep": ""})
        if generated == "node":
            self.compile(root)
        elif generated == "fixture":
            write_projections(root)
        return root

    def compile(self, root: Path) -> None:
        if NODE is None:
            self.skipTest("node is not on PATH")
        done = subprocess.run(
            [NODE, str(BIN), "compile", "--json"],
            env={**os.environ, "HOUSE_ROOT": str(root)},
            capture_output=True,
            encoding="utf-8",
            check=False,
        )
        self.assertEqual(done.returncode, 0, done.stdout + done.stderr)


FIXTURE_KERNEL = (
    "Purpose: Keep the test honest.\n\nPrinciples:\n- A Care: Look before acting. Failure mode: Haste.\n\n"
    "Ask first:\n- deleting files"
)


def write_projections(root: Path, kernel: str = FIXTURE_KERNEL, worker_reflexes: str = "") -> None:
    """kernel.md, router.hermes.md and worker.hermes.md as the compiler lays them out: header, marker, K, sections."""
    specs = "house.toml, principles/*.md, charter/core.md, charter/provisions/*.md, reflexes/*.md, voice.md"
    digest = input_hash(str(root), input_paths(str(root), specs.split(", ")))
    header = f"<!-- GENERATED by lampstand from {specs}; input-hash {digest}; do not edit -->"
    worker = f"\n\n## Reflexes\n\n{worker_reflexes}" if worker_reflexes else ""
    plant(
        root,
        {
            ".house/generated/kernel.md": f"{header}\n<!-- lampstand:kernel -->\n{kernel}\n",
            ".house/generated/router.hermes.md": f"{header}\n<!-- lampstand:router:hermes -->\n{kernel}\n",
            ".house/generated/worker.hermes.md": f"{header}\n<!-- lampstand:worker:hermes -->\n{kernel}{worker}\n",
        },
    )


class RecordingContext:
    """The parts of Hermes's plugin ctx the adapter uses, recording what register() hands over."""

    def __init__(self, cwd: str = "", surface: str = "cli", lifecycle: object = None) -> None:
        self.sections: dict[str, tuple] = {}
        self.hooks: dict[str, object] = {}
        self.tools: dict[str, dict] = {}
        self.cwd = cwd
        self.surface = surface
        if lifecycle is not None:
            self.subagent_lifecycle = lifecycle

    def register_system_prompt_section(self, id, content, *, position="after_memory", max_chars=4000):
        self.sections[id] = (content, max_chars)

    def register_hook(self, hook_name, callback, *, hold_stream=False):
        self.hooks[hook_name] = callback

    def register_tool(self, name, toolset, schema, handler, **kwargs):
        self.tools[name] = {"toolset": toolset, "schema": schema, "handler": handler, **kwargs}

    def session_cwd(self) -> str:
        return self.cwd

    def session_surface(self) -> str:
        return self.surface
