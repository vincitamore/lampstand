// @ts-check
// A newer lampstand is stood in for by a copy of this package whose templates or pack a test changes.
import assert from "node:assert/strict";
import { appendFileSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { contentHash } from "../../core/lib/io.js";
import { parseFrontmatter } from "../../core/lib/frontmatter.js";
import { answersToml, copyPackage, envelope, isolatedEnv, lampstand, read, SLOW, tempDir, treeHash } from "./helpers.js";

/** @param {import("./helpers.js").TestContext} t */
function setup(t) {
  const dir = tempDir(t);
  const house = join(dir, "house");
  const env = isolatedEnv(dir);
  writeFileSync(join(dir, "answers.toml"), answersToml());
  const planted = lampstand(["init", "house", "--answers", "answers.toml"], { cwd: dir, env, entryDir: dir });
  assert.equal(planted.status, 0, planted.stdout + planted.stderr);
  const pkg = copyPackage(join(dir, "pkg"));
  /** @param {string[]} args @param {string} [from]  the package that runs */
  const run = (args, from = pkg) => lampstand(args, { cwd: house, env, pkg: from, entryDir: dir });
  return { dir, house, env, pkg, run };
}

test("upgrade replaces unedited planted files, and gives an edited one a proposal while keeping every byte of it", SLOW, (t) => {
  const s = setup(t);
  appendFileSync(join(s.pkg, "templates", "constitution", "charter", "core.rules.md"), "- A provision names the gate that checks it.\n");
  appendFileSync(join(s.pkg, "templates", "constitution", "curation.md"), "\nA newer curation line.\n");
  writeFileSync(join(s.pkg, "templates", "root", "AGENTS.md"), read(s.pkg, "templates/root/AGENTS.md").replace("# AGENTS.md\n", "# AGENTS.md\n\nA newer preface.\n"));
  appendFileSync(join(s.house, "charter", "core.md"), "\nOur own rule about Fridays.\n");
  const edited = read(s.house, "charter/core.md");

  const result = s.run(["upgrade", "--json"]);
  assert.equal(result.status, 0, result.stdout + result.stderr);
  const data = envelope(result.stdout);
  assert.deepEqual(data.migrations, []);
  assert.deepEqual(data.updated, ["curation.md", "AGENTS.md"]);
  assert.deepEqual(data.proposed, ["proposals/updates/charter/core.md"]);
  assert.equal(data.region, "written");

  assert.equal(read(s.house, "charter/core.md"), edited, "the edited file is left exactly as it was");
  assert.equal(read(s.house, "curation.md"), read(s.pkg, "templates/constitution/curation.md"));
  const agents = read(s.house, "AGENTS.md");
  assert.ok(agents.startsWith("# AGENTS.md\n\nA newer preface.\n"));
  assert.match(agents, /<!-- house:begin -->\n<!-- GENERATED by lampstand from [^\n]+\n<!-- lampstand:kernel -->\n/);

  const proposal = parseFrontmatter(read(s.house, "proposals/updates/charter/core.md"), "proposal");
  const upstream = read(s.pkg, "templates/constitution/charter/core.rules.md");
  assert.equal(proposal.frontmatter?.updates, "charter/core.md");
  assert.equal(proposal.frontmatter?.["upstream-sha256"], contentHash(upstream));
  assert.ok(proposal.body.includes(`\n\`\`\`\n${upstream}\`\`\`\n`), "the new text is carried whole");

  assert.equal(s.run(["compile", "--check"]).status, 0);
  const backups = readdirSync(join(data.backup, ".."));
  assert.equal(backups.length, 1);
  assert.ok(existsSync(join(data.backup, "house.toml")) && existsSync(join(data.backup, ".house", "planted.json")));

  const before = treeHash(s.house);
  const again = envelope(s.run(["upgrade", "--json"]).stdout);
  assert.deepEqual([again.updated, again.proposed, again.planted], [[], [], []], "each change is offered once");
  assert.equal(treeHash(s.house), before);
});

test("upgrade plants a file new in this lampstand, and not one the operator removed", SLOW, (t) => {
  const s = setup(t);
  writeFileSync(join(s.pkg, "templates", "root", "WATCHDOG.md"), "# Watchdog\n");
  const manifest = JSON.parse(read(s.pkg, "templates/root/manifest.json"));
  manifest.files.push({ template: "WATCHDOG.md", destination: "WATCHDOG.md" });
  writeFileSync(join(s.pkg, "templates", "root", "manifest.json"), JSON.stringify(manifest));
  appendFileSync(join(s.pkg, "templates", "constitution", "state", "current.md"), "\nNewer.\n");
  rmSync(join(s.house, "state", "current.md"));

  const data = envelope(s.run(["upgrade", "--json"]).stdout);
  assert.deepEqual([data.planted, data.updated, data.proposed], [["WATCHDOG.md"], [], []]);
  assert.equal(read(s.house, "WATCHDOG.md"), "# Watchdog\n");
  assert.ok(!existsSync(join(s.house, "state", "current.md")));
  assert.equal(JSON.parse(read(s.house, ".house/planted.json")).files["WATCHDOG.md"].sha256, contentHash("# Watchdog\n"));
});

/** A house planted before projects/README.md existed: the file and its planted.json record are gone. @param {string} house */
function forgetProjectsReadme(house) {
  rmSync(join(house, "projects"), { recursive: true, force: true });
  const planted = JSON.parse(read(house, ".house/planted.json"));
  delete planted.files["projects/README.md"];
  writeFileSync(join(house, ".house", "planted.json"), JSON.stringify(planted, null, 2) + "\n");
}

test("upgrade leaves an operator's own projects/README.md alone", SLOW, (t) => {
  const s = setup(t);
  forgetProjectsReadme(s.house);
  mkdirSync(join(s.house, "projects"), { recursive: true });
  const own = "# What we build\n\nOur own words.\n";
  writeFileSync(join(s.house, "projects", "README.md"), own);

  const data = envelope(s.run(["upgrade", "--json"]).stdout);
  assert.deepEqual([data.planted, data.updated, data.proposed], [[], [], []]);
  assert.equal(read(s.house, "projects/README.md"), own);
  assert.equal(JSON.parse(read(s.house, ".house/planted.json")).files["projects/README.md"], undefined, "a file upgrade did not write is not recorded as planted");
});

test("upgrade refuses a house whose [plugin] min or schema is newer than this lampstand, writing nothing", SLOW, (t) => {
  const s = setup(t);
  const toml = read(s.house, "house.toml");
  /** @type {Array<[string, string]>} */
  const cases = [
    [toml.replace(/^min = ".*"$/m, 'min = "99.0.0"'), "E_PLUGIN_TOO_OLD"],
    [toml.replace(/^schema = 1$/m, "schema = 2"), "E_SCHEMA_NEWER"],
  ];
  for (const [newer, code] of cases) {
    writeFileSync(join(s.house, "house.toml"), newer);
    const before = treeHash(s.house);
    const result = s.run(["upgrade", "--json"]);
    assert.equal(result.status, 1, result.stdout + result.stderr);
    assert.equal(envelope(result.stdout).error.code, code);
    assert.equal(treeHash(s.house), before);
    assert.ok(!existsSync(join(s.dir, "state-root")), "no backup was taken");
  }
});

test("a changed lattice pack is never written over the house's copy: unedited gets the new text proposed, edited a note", SLOW, (t) => {
  const s = setup(t);
  appendFileSync(join(s.pkg, "packs", "lattice", "LATTICE.md"), "\nA newer closing paragraph.\n");
  const lattice = read(s.house, "principles/lattice.md");

  const unedited = envelope(s.run(["upgrade", "--json"]).stdout);
  assert.deepEqual(unedited.proposed, ["proposals/updates/principles/lattice.md"]);
  assert.equal(read(s.house, "principles/lattice.md"), lattice);
  const offered = read(s.house, "proposals/updates/principles/lattice.md");
  assert.ok(offered.includes("A newer closing paragraph."));
  assert.ok(offered.includes(`adopted-hash: "${contentHash(read(s.pkg, "packs/lattice/LATTICE.md").replaceAll("\r\n", "\n"))}"`));

  appendFileSync(join(s.house, "principles", "lattice.md"), "\nOur own closing line.\n");
  const editedCopy = read(s.house, "principles/lattice.md");
  envelope(s.run(["upgrade", "--json"]).stdout);
  assert.equal(read(s.house, "principles/lattice.md"), editedCopy);
  const note = read(s.house, "proposals/updates/principles/lattice.md");
  assert.match(note, /# The lattice pack changed/);
  assert.ok(!note.includes("A newer closing paragraph."), "an edited copy gets a note, not the text");
});

test("a pack that reworded a principle's *Kernel:* line is offered as an update proposal; the house's copy and its kernel stay as they were", SLOW, (t) => {
  const s = setup(t);
  const packPath = join(s.pkg, "packs", "lattice", "LATTICE.md");
  const pack = read(s.pkg, "packs/lattice/LATTICE.md");
  const before = /^\*Kernel:\* (.+)$/m.exec(pack);
  assert.ok(before, "the shipped pack carries kernel lines");
  writeFileSync(packPath, pack.replace(before[0], "*Kernel:* A reworded kernel line from a newer pack."));
  const lattice = read(s.house, "principles/lattice.md");
  const kernel = read(s.house, ".house/generated/kernel.md");

  const result = envelope(s.run(["upgrade", "--json"]).stdout);
  assert.deepEqual(result.proposed, ["proposals/updates/principles/lattice.md"]);
  assert.equal(read(s.house, "principles/lattice.md"), lattice, "the operator's copy is theirs");
  assert.equal(read(s.house, ".house/generated/kernel.md"), kernel, "the kernel still carries the adopted line");
  assert.ok(read(s.house, "proposals/updates/principles/lattice.md").includes("*Kernel:* A reworded kernel line from a newer pack."));
  assert.equal(s.run(["compile", "--check"]).status, 0);
});
