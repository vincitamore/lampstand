// @ts-check
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { chars } from "../../core/lib/constitution/budgets.js";
import { runCompile } from "../../core/lib/constitution/run.js";
import { agentsRegionStale, blankRegion, REGION_CAP, renderRegion, writeAgentsRegion } from "../../core/lib/init/region.js";
import { plant, plantHouse, reflexFile } from "../u2/helpers.js";
import { tempDir } from "./helpers.js";

const AGENTS = "# Ours\n\nBefore.\n<!-- house:begin -->\n<!-- house:end -->\nAfter.\n";

/** The section markers of a region, in order, by section name. @param {string} region */
const sections = (region) => [...region.matchAll(/^<!-- lampstand:section:([a-z]+) -->$/gm)].map((match) => match[1]);

test("the region carries K first, then whole router sections in order, skipping one that would overflow 12,000 chars", (t) => {
  const root = tempDir(t);
  plantHouse(root);
  const run = runCompile(root);
  assert.deepEqual(run.errors, []);
  const region = renderRegion(run.compiled);
  const lines = region.split("\n");
  assert.match(lines[0], /^<!-- GENERATED by lampstand from .+; input-hash [0-9a-f]{64}; do not edit -->$/);
  assert.equal(lines[1], "<!-- lampstand:kernel -->");
  assert.ok(region.startsWith(`${lines[0]}\n${lines[1]}\n${run.compiled.kernel}\n\n`), "K comes first, byte for byte");
  // The lattice's principle detail (over 33,000 chars) cannot fit; charter and voice after it still do.
  assert.ok(run.compiled.manifest.surfaces["principle-detail"].chars > REGION_CAP);
  assert.deepEqual(sections(region), ["charter", "voice"]);
  assert.ok(region.includes("<!-- lampstand:section:charter -->\n## Charter\n\n# Charter\n\nThis house makes rules in `rules` mode."));
  assert.ok(region.includes("<!-- lampstand:section:voice -->\n## Voice\n\n# Voice\n\nCollaboration manners and per-channel norms. The agent adds to this file only from what it has observed of the\noperator, never from guesses. Each channel's norms go under a `## <channel>` heading.\n\n## chat\n\nShort answers; no headings.\n\n"));
  // A host without the OMP adapter loads only the region, so it names what it left out and where to read it.
  assert.match(region, /\n\nNot in this region, for size or because it differs between hosts: Principle detail \(`principles\/`\)\. [^\n]+$/);
  assert.ok(chars(region) <= REGION_CAP);

  const small = tempDir(t);
  plantHouse(small, { lattice: false, profile: "standard" });
  const all = renderRegion(runCompile(small).compiled);
  assert.deepEqual(sections(all), ["charter", "voice"], "an empty section is not carried");
  assert.ok(!all.includes("Not in this region"), "an empty section is not reported as left out");
  plant(small, {
    "principles/own.md": `---\norigin: "own"\noccasion: "o"\nadopted: "2026-11-02"\nadopted-hash: "${"0".repeat(64)}"\n---\n### M : Mine\n\n*Thesis.*\n\n- **f**: g\n\n*Vice:* v.\n`,
  });
  assert.deepEqual(sections(renderRegion(runCompile(small).compiled)), ["principles", "charter", "voice"]);
});

test("a reflex section is carried only when every host's index is the same", (t) => {
  const root = tempDir(t);
  plantHouse(root, { lattice: false, profile: "standard" });
  plant(root, { "reflexes/check-first.md": reflexFile("check-first", "behavioral") });
  assert.deepEqual(sections(renderRegion(runCompile(root).compiled)), ["charter", "reflexes", "voice"]);
  plant(root, { "reflexes/omp-only.md": reflexFile("omp-only", "tool:omp") });
  const scoped = renderRegion(runCompile(root).compiled);
  assert.deepEqual(sections(scoped), ["charter", "voice"]);
  assert.match(scoped, /Not in this region, for size or because it differs between hosts: Reflexes \(`reflexes\/`\)\./);
});

test("writing the region changes only the bytes between the markers, and writes nothing when it is current", (t) => {
  const root = tempDir(t);
  plantHouse(root);
  writeFileSync(join(root, "AGENTS.md"), AGENTS);
  // check mode: the compiled result without writing, so the region is still stale when the writer is exercised.
  const { compiled } = runCompile(root, { check: true });
  assert.equal(agentsRegionStale(root, compiled), true);
  assert.equal(writeAgentsRegion(root, compiled).status, "written");
  const text = readFileSync(join(root, "AGENTS.md"), "utf8");
  assert.equal(text, `# Ours\n\nBefore.\n<!-- house:begin -->\n${renderRegion(compiled)}\n<!-- house:end -->\nAfter.\n`);
  assert.equal(blankRegion(text), AGENTS);
  assert.equal(agentsRegionStale(root, compiled), false);
  assert.equal(writeAgentsRegion(root, compiled).status, "unchanged");
});

test("markers that are missing, doubled or out of order leave AGENTS.md untouched", (t) => {
  const root = tempDir(t);
  plantHouse(root);
  const { compiled } = runCompile(root);
  for (const text of [
    "# No markers\n",
    "<!-- house:begin -->\n<!-- house:begin -->\n<!-- house:end -->\n",
    "<!-- house:end -->\n<!-- house:begin -->\n",
    "inline <!-- house:begin --> marker\n<!-- house:end -->\n",
  ]) {
    writeFileSync(join(root, "AGENTS.md"), text);
    assert.equal(writeAgentsRegion(root, compiled).status, "no-region", JSON.stringify(text));
    assert.equal(readFileSync(join(root, "AGENTS.md"), "utf8"), text);
  }
});
