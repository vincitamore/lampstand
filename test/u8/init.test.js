/**
 * A temp layout: the entry script and roots at the top, the house in `house/`, the answers beside it.
 * @param {import("./helpers.js").TestContext} t
 * @param {string} [answers]
 */
function setup(t, answers = answersToml()) {
  const dir = tempDir(t);
  const house = join(dir, "house");
  writeFileSync(join(dir, "answers.toml"), answers);
  const env = isolatedEnv(dir);
  /** @param {string[]} args @param {string} [cwd] */
  const run = (args, cwd = dir) => lampstand(args, { cwd, env, entryDir: dir });
  return { dir, house, env, run };
}

test("init with an answers file plants a house that compiles fresh and lints clean, and a re-run changes no byte", SLOW, (t) => {
  const s = setup(t);
  const first = s.run(["init", "house", "--answers", "answers.toml", "--json"]);
  assert.equal(first.status, 0, first.stdout + first.stderr);
  const result = envelope(first.stdout);
  assert.equal(result.git, "initialized");
  assert.equal(result.region, "written");
  assert.deepEqual([...result.planted].sort(), [
    ".gitattributes",
    ".gitignore",
    "AGENTS.md",
    "charter/core.md",
    "charter/record.md",
    "curation.md",
    "house.toml",
    "principles/lattice.md",
    "reflexes/INDEX.md",
    "state/current.md",
    "voice.md",
  ]);
  assert.ok(existsSync(join(s.house, ".git")));

  const check = s.run(["compile", "--check"], s.house);
  assert.equal(check.status, 0, check.stdout + check.stderr);
  const lint = s.run(["lint"], s.house);
  assert.equal(lint.status, 0, lint.stdout + lint.stderr);

  const toml = read(s.house, "house.toml");
  assert.match(toml, /\[budget\]\nprofile = "large"\n/);
  assert.match(toml, /\[charter\]\nmode = "rules"\nask_first = \[/);
  assert.deepEqual(parseToml(toml, "house.toml").charter, { mode: "rules", ask_first: [...DEFAULT_ASK_FIRST, "Ask before pushing to any remote."] });
  assert.match(read(s.house, "voice.md"), /\n## chat\nShort replies\.\n$/);
  assert.equal(read(s.house, "charter/core.md"), read(REPO, "templates/constitution/charter/core.rules.md").replaceAll("\r\n", "\n"));

  const lattice = parseFrontmatter(read(s.house, "principles/lattice.md"), "lattice.md");
  const pack = read(REPO, "packs/lattice/LATTICE.md").replaceAll("\r\n", "\n");
  assert.equal(lattice.body, pack, "the pack is planted verbatim");
  assert.equal(lattice.frontmatter?.origin, "pack:lattice@1");
  assert.match(String(lattice.frontmatter?.adopted), /^\d{4}-\d{2}-\d{2}$/);
  assert.equal(lattice.frontmatter?.["adopted-hash"], contentHash(pack));

  const planted = JSON.parse(read(s.house, ".house/planted.json"));
  assert.deepEqual(Object.keys(planted.files).sort(), [...result.planted].sort());
  assert.equal(planted.files["voice.md"].sha256, contentHash(read(s.house, "voice.md")));

  const before = treeHash(s.house);
  const again = s.run(["init", "house", "--answers", "answers.toml", "--json"]);
  assert.equal(again.status, 0, again.stdout + again.stderr);
  assert.deepEqual(envelope(again.stdout).planted, []);
  assert.equal(treeHash(s.house), before, "a second init changes no byte, .git included");
});

test("a file already in the target is never overwritten, and a planted file the operator removed is not planted again", SLOW, (t) => {
  const s = setup(t);
  const own = "# Our voice\n\nWe write plainly.\n";
  const agents = "# Our agents\r\n\r\nKeep this.\r\n<!-- house:begin -->\r\nold region\r\n<!-- house:end -->\r\nAnd this, after.\r\n";
  plant(s.house, { "voice.md": own, "AGENTS.md": agents });

  const first = s.run(["init", "house", "--answers", "answers.toml", "--json"]);
  assert.equal(first.status, 0, first.stdout + first.stderr);
  const result = envelope(first.stdout);
  assert.deepEqual(result.kept.sort(), ["AGENTS.md", "voice.md"]);
  assert.equal(read(s.house, "voice.md"), own);
  const text = read(s.house, "AGENTS.md");
  assert.ok(text.startsWith("# Our agents\r\n\r\nKeep this.\r\n<!-- house:begin -->\r\n<!-- GENERATED by lampstand from "));
  assert.ok(text.endsWith("\r\n<!-- house:end -->\r\nAnd this, after.\r\n"), "every byte after the region is kept");
  assert.ok(!text.includes("old region"));
  const plantedFiles = JSON.parse(read(s.house, ".house/planted.json")).files;
  assert.equal(plantedFiles["voice.md"], undefined, "a file init did not write is not recorded as planted");

  rmSync(join(s.house, "principles", "lattice.md"));
  rmSync(join(s.house, "curation.md"));
  const again = s.run(["init", "house", "--json"]);
  assert.equal(again.status, 0, again.stdout + again.stderr);
  assert.deepEqual(envelope(again.stdout).removed, ["curation.md"]);
  assert.ok(!existsSync(join(s.house, "principles", "lattice.md")), "a struck lattice stays struck");
});

