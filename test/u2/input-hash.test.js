// @ts-check
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { generatedHeader } from "../../core/lib/constitution/compile.js";
import { INPUT_SPECS, inputHash, readInputs } from "../../core/lib/constitution/house.js";
import { isolatedEnv, lampstand, plant, plantHouse, REPO, tempDir } from "./helpers.js";

const VECTORS = JSON.parse(readFileSync(join(REPO, "schema", "constitution", "input-hash.json"), "utf8")).vectors;

for (const vector of VECTORS) {
  test(`input hash vector: ${vector.name}`, (t) => {
    const root = tempDir(t);
    plant(root, vector.files);
    const inputs = readInputs(root);
    assert.deepEqual(inputs.map((input) => input.path), vector["input-paths"]);
    assert.equal(inputHash(inputs), vector["input-hash"]);
  });
}

test("the header names exactly the input specs the vectors are defined over", () => {
  assert.equal(
    generatedHeader("0".repeat(64)),
    `<!-- GENERATED by lampstand from ${INPUT_SPECS.join(", ")}; input-hash ${"0".repeat(64)}; do not edit -->`,
  );
  assert.deepEqual([...INPUT_SPECS], ["house.toml", "principles/*.md", "charter/core.md", "charter/provisions/*.md", "reflexes/*.md", "voice.md"]);
});

test("declaring a job or turning a module on leaves a compiled house fresh; changing the purpose or ask_first makes it stale", (t) => {
  const root = tempDir(t);
  plantHouse(root);
  const env = isolatedEnv(root);
  assert.equal(lampstand(["compile"], { cwd: root, env }).status, 0);
  const check = () => lampstand(["compile", "--check"], { cwd: root, env }).status;
  const toml = readFileSync(join(root, "house.toml"), "utf8");
  const before = inputHash(readInputs(root));

  writeFileSync(join(root, "house.toml"), `${toml}\n[modules]\nscheduler = true\n\n[gate]\nmode = "block"\n\n# nightly\n[jobs.check]\nargv = ["lampstand", "doctor", "--quick"]\nevery = "1h"\nstale_hours = 48\n`);
  assert.equal(inputHash(readInputs(root)), before);
  assert.equal(check(), 0, "a jobs edit is not stale");

  writeFileSync(join(root, "house.toml"), toml.replace("The work is for", "The work is really for"));
  assert.notEqual(inputHash(readInputs(root)), before);
  assert.equal(check(), 1, "a changed purpose is stale");

  writeFileSync(join(root, "house.toml"), toml.replace("Ask before pushing to any remote.", "Ask before pushing anywhere."));
  assert.notEqual(inputHash(readInputs(root)), before);
  assert.equal(check(), 1, "a changed ask_first line is stale");
});
