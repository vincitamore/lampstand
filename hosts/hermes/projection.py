"""Reads a generated projection from .house/generated/ after verifying the input hash its header names.

The hash is defined in schema/constitution/input-hash.json: sha256 over, for each present input in spec order,
`<house-relative path>\\n<content hash>\\n`, where the content hash is sha256 of the file's text with one leading BOM
removed and CRLF turned into LF (schema/conformance/hash). A stale projection is still loaded; it carries a notice.
"""

from __future__ import annotations

import hashlib
import os
import re
from dataclasses import dataclass

from .root import read_text

GENERATED_DIR = (".house", "generated")
HEADER = re.compile(r"^<!-- GENERATED by lampstand from (.+); input-hash ([0-9a-f]{64}); do not edit -->$")
MARKER = re.compile(r"^<!-- lampstand:[a-z]+(?::[a-z]+)? -->$")


class ProjectionError(Exception):
    """A projection that cannot be loaded at all: missing, unreadable, or without its header and marker."""


def content_hash(raw: bytes) -> str:
    text = raw.decode("utf-8").removeprefix("\ufeff")
    return hashlib.sha256(text.replace("\r\n", "\n").encode("utf-8")).hexdigest()


def input_paths(root: str, specs: list[str]) -> list[str]:
    """The house-relative inputs present for `specs`: a `<dir>/*.md` spec is every regular .md file directly in that
    directory in code point order of its name; any other spec is one file, skipped when absent."""
    paths: list[str] = []
    for spec in specs:
        if spec.endswith("/*.md"):
            folder = spec[: -len("/*.md")]
            directory = os.path.join(root, *folder.split("/"))
            try:
                entries = os.listdir(directory)
            except OSError:
                continue
            names = sorted(n for n in entries if n.endswith(".md") and os.path.isfile(os.path.join(directory, n)))
            paths.extend(f"{folder}/{name}" for name in names)
        elif os.path.isfile(os.path.join(root, *spec.split("/"))):
            paths.append(spec)
    return paths


def input_hash(root: str, paths: list[str]) -> str:
    digest = hashlib.sha256()
    for path in paths:
        with open(os.path.join(root, *path.split("/")), "rb") as handle:
            digest.update(f"{path}\n{content_hash(handle.read())}\n".encode())
    return digest.hexdigest()


@dataclass(frozen=True)
class Projection:
    name: str
    path: str
    text: str  # the whole file, LF-normalized
    recorded_hash: str
    current_hash: str

    @property
    def stale(self) -> bool:
        return self.recorded_hash != self.current_hash

    @property
    def body(self) -> str:
        """Everything after the GENERATED header: the marker line, then K, then the projection's sections."""
        return self.text.split("\n", 1)[1]

    @property
    def marker(self) -> str:
        return self.body.split("\n", 1)[0]

    @property
    def notice(self) -> str | None:
        if not self.stale:
            return None
        return (
            f"lampstand: {self.name} is stale (built from input-hash {self.recorded_hash[:12]}, the house is now "
            f"{self.current_hash[:12]}); it is loaded as is, run `lampstand compile` to refresh it."
        )


def projection_path(root: str, name: str) -> str:
    return os.path.join(root, *GENERATED_DIR, name)


def read_projection(root: str, name: str) -> Projection:
    """Reads `.house/generated/<name>` under `root` and recomputes its input hash. Raises ProjectionError."""
    path = projection_path(root, name)
    try:
        text = read_text(path)
    except FileNotFoundError as error:
        message = f"lampstand: {name} has not been generated; run `lampstand compile` in {root}."
        raise ProjectionError(message) from error
    except (OSError, UnicodeDecodeError) as error:
        message = f"lampstand: {name} cannot be read ({error}); run `lampstand compile` in {root}."
        raise ProjectionError(message) from error
    lines = text.split("\n", 2)
    header = HEADER.match(lines[0])
    if header is None or len(lines) < 2 or MARKER.match(lines[1]) is None:
        raise ProjectionError(
            f"lampstand: {name} does not open with the lampstand header and marker; run `lampstand compile` in {root}."
        )
    try:
        current = input_hash(root, input_paths(root, header.group(1).split(", ")))
    except (OSError, UnicodeDecodeError) as error:
        raise ProjectionError(f"lampstand: the inputs of {name} cannot be read ({error}).") from error
    return Projection(name=name, path=path, text=text, recorded_hash=header.group(2), current_hash=current)
