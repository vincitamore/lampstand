// @ts-check
// The compiler: a pure function from a parsed house to its projections.
//
//   K  kernel     purpose, one line per adopted principle (mark, name, thesis, failure mode), the ask-first lines
//   R  router     K, principle detail, charter core (with the provisions in force), the host's reflexes, voice
//   W  worker     K, the reflexes that load on the host, in full
//   G  watchdog   K, each principle's failure mode in full, the ask-first lines
//
// K is rendered once and its bytes are placed first in every projection. Reflexes are host-scoped, so R and W exist
// once per host. Every projection opens with the GENERATED header naming the inputs and their hash, then a marker
// line naming the projection, which is what a host checks before injecting it so it is never carried twice.
import { BUDGETS, capOf, chars, hostLimit, KERNEL_FRAMING_CHARS, KERNEL_TARGET, surfaceOf, tokensEstimate } from "./budgets.js";
import { contentHash } from "../io.js";
import { INPUT_SPECS } from "./house.js";
import { HOSTS, reflexAppliesTo } from "./parse.js";

/** @typedef {import("./house.js").House} House */
/** @typedef {{ chars: number, tokens: number, cap: number, target?: number }} SurfaceSize */
/**
 * @typedef {{
 *   generator: "lampstand",
 *   profile: import("./budgets.js").Profile,
 *   "input-hash": string,
 *   inputs: string[],
 *   surfaces: Record<string, SurfaceSize>,
 *   projections: Record<string, { chars: number, sha256: string }>,
 * }} Manifest
 * @typedef {{ name: string, text: string }} GeneratedFile
 * @typedef {{ kernel: string, files: GeneratedFile[], manifest: Manifest }} Compiled
 */

export const GENERATED_DIR = ".house/generated";
export const MANIFEST_FILE = "manifest.json";

/** @param {string} inputHash */
export function generatedHeader(inputHash) {
  return `<!-- GENERATED by lampstand from ${INPUT_SPECS.join(", ")}; input-hash ${inputHash}; do not edit -->`;
}

/** The header of a projection read back from disk, or null. @param {string} text */
export function readHeader(text) {
  const first = text.slice(0, text.indexOf("\n") < 0 ? text.length : text.indexOf("\n"));
  const match = /^<!-- GENERATED by lampstand from (.+); input-hash ([0-9a-f]{64}); do not edit -->$/.exec(first);
  return match ? { inputs: match[1].split(", "), inputHash: match[2] } : null;
}

/**
 * The marker line of a projection: `kernel`, `watchdog`, `router:<host>` or `worker:<host>`.
 * @param {string} projection
 */
export function projectionMarker(projection) {
  return `<!-- lampstand:${projection} -->`;
}

/**
 * Appends a projection's text to a host's context unless the context already carries that projection's marker.
 * @param {string} context
 * @param {string} projectionText  a generated projection, as written to disk
 */
export function withProjection(context, projectionText) {
  const marker = projectionText.split("\n", 2)[1] ?? "";
  if (!/^<!-- lampstand:[a-z]+(?::[a-z]+)? -->$/.test(marker)) throw new Error("not a lampstand projection: its second line is not a marker");
  if (context.split("\n").includes(marker)) return context;
  return context === "" ? projectionText : `${context.endsWith("\n") ? context : `${context}\n`}\n${projectionText}`;
}

/**
 * The kernel: the purpose, one line per principle (its `*Kernel:*` line when it has one, else its thesis and failure
 * mode), and the ask-first lines.
 * @param {House} house
 */
export function renderKernel(house) {
  const parts = [];
  if (house.purpose.text !== "") parts.push(`Purpose: ${house.purpose.text}`);
  const principles = house.principleFiles.flatMap((file) => file.principles);
  if (principles.length > 0) {
    const lines = principles.map((p) => {
      if (p.kernel !== null) return `- ${p.mark} ${p.name}: ${p.kernel}`;
      const failure = p.failureMode ? ` Failure mode: ${withStop(p.failureMode.summary)}` : "";
      return `- ${p.mark} ${p.name}: ${p.thesis}${failure}`;
    });
    parts.push(`Principles:\n${lines.join("\n")}`);
  }
  if (house.askFirst.length > 0) parts.push(`Ask first:\n${house.askFirst.map((line) => `- ${line}`).join("\n")}`);
  return parts.join("\n\n");
}

/** @param {string} text */
function withStop(text) {
  return /[.!?]$/.test(text) ? text : `${text}.`;
}

/**
 * A principle file's text without its `*Kernel:*` paragraphs: the kernel already carries that line in every session,
 * so the detail beside it would only repeat it.
 * @param {string} body
 */
export function withoutKernelLines(body) {
  const out = [];
  const lines = body.split("\n");
  for (let k = 0; k < lines.length; k++) {
    if (!/^\*Kernel:\*/.test(lines[k])) {
      out.push(lines[k]);
      continue;
    }
    while (k + 1 < lines.length && lines[k + 1].trim() !== "") k++;
    if (k + 1 < lines.length) k++; // the blank line that ended the paragraph
  }
  return out.join("\n");
}

/** @param {House} house */
function principleDetail(house) {
  return house.principleFiles.map((file) => withoutKernelLines(file.body)).join("\n\n");
}

/** @param {House} house */
function charterCore(house) {
  const parts = house.charterCore ? [house.charterCore] : [];
  for (const provision of house.provisions) parts.push(`### ${provision.title}\n\n${provision.text}`.trim());
  return parts.join("\n\n");
}

/** @param {House} house @param {string} host */
function reflexesOn(house, host) {
  return house.reflexes.filter((reflex) => reflexAppliesTo(reflex.scope, host));
}

/** @param {import("./parse.js").Reflex} reflex */
function reflexInFull(reflex) {
  return [`### ${reflex.slug} (${reflex.scope})`, reflex.summary, reflex.body].filter((part) => part !== "").join("\n\n");
}

/**
 * The router's reflex section: the index preface, then one index line per reflex, or with `[reflexes] router =
 * "full"` each reflex in full as W carries it. Either way it is one section, measured as the reflex-index surface.
 * @param {House} house @param {string} host
 */
function routerReflexes(house, host) {
  const reflexes = reflexesOn(house, host);
  if (reflexes.length === 0) return "";
  const entries =
    house.config.reflexes?.router === "full"
      ? reflexes.map(reflexInFull).join("\n\n")
      : reflexes.map((reflex) => `- ${reflex.slug} (${reflex.scope}): ${reflex.summary}`).join("\n");
  return [house.reflexIndex ?? "", entries].filter((part) => part !== "").join("\n\n");
}

/** @param {House} house @param {string} host */
function workerReflexes(house, host) {
  return reflexesOn(house, host).map(reflexInFull).join("\n\n");
}

/** @param {House} house */
function failureModes(house) {
  return house.principleFiles
    .flatMap((file) => file.principles)
    .filter((p) => p.failureMode !== null)
    .map((p) => `- ${p.mark} ${p.name}: ${/** @type {import("./parse.js").FailureMode} */ (p.failureMode).text}`)
    .join("\n");
}

/**
 * Header, marker, K, then each non-empty `## <title>` section.
 * @param {string} header
 * @param {string} projection
 * @param {string} kernel
 * @param {[string, string][]} sections
 */
function assemble(header, projection, kernel, sections) {
  const rest = sections.filter(([, body]) => body !== "").map(([title, body]) => `## ${title}\n\n${body}`);
  return `${[`${header}\n${projectionMarker(projection)}\n${kernel}`, ...rest].join("\n\n")}\n`;
}

/**
 * Compiles a parsed house into its projections and manifest. Pure: the same house gives the same bytes.
 * @param {House} house
 * @returns {Compiled}
 */
export function compileHouse(house) {
  const header = generatedHeader(house.inputHash);
  const kernel = renderKernel(house);
  /** @type {Record<string, SurfaceSize>} */
  const surfaces = {};
  /** @param {string} key @param {number} n */
  const measure = (key, n) => {
    surfaces[key] = { chars: n, tokens: tokensEstimate(n), cap: capOf(key, house.profile, house.surfaces) };
    if (surfaceOf(key) === "kernel") surfaces[key].target = KERNEL_TARGET[house.profile];
  };

  measure("kernel", KERNEL_FRAMING_CHARS + chars(kernel));
  const detail = principleDetail(house);
  const charter = charterCore(house);
  const voice = house.voice?.text ?? "";
  measure("principle-detail", chars(detail));
  measure("charter-core", chars(charter));

  /** @type {GeneratedFile[]} */
  const files = [{ name: "kernel.md", text: assemble(header, "kernel", kernel, []) }];
  for (const host of HOSTS) {
    const index = routerReflexes(house, host);
    measure(`reflex-index:${host}`, chars(index));
    files.push({
      name: `router.${host}.md`,
      text: assemble(header, `router:${host}`, kernel, [
        ["Principle detail", detail],
        ["Charter", charter],
        ["Reflexes", index],
        ["Voice", voice],
      ]),
    });
  }
  measure("voice", chars(voice));
  for (const host of HOSTS) {
    const prefix = `${header}\n${projectionMarker(`worker:${host}`)}\n${kernel}`;
    const text = assemble(header, `worker:${host}`, kernel, [["Reflexes", workerReflexes(house, host)]]);
    measure(`worker:${host}`, chars(text) - chars(prefix) - 1);
    files.push({ name: `worker.${host}.md`, text });
  }
  const asks = house.askFirst.map((line) => `- ${line}`).join("\n");
  files.push({
    name: "watchdog.md",
    text: assemble(header, "watchdog", kernel, [
      ["Failure modes", failureModes(house)],
      ["Ask first", asks],
    ]),
  });

  /** @type {Manifest} */
  const manifest = {
    generator: "lampstand",
    profile: house.profile,
    "input-hash": house.inputHash,
    inputs: house.inputs,
    surfaces,
    projections: Object.fromEntries(files.map((file) => [file.name, { chars: chars(file.text), sha256: contentHash(file.text) }])),
  };
  files.push({ name: MANIFEST_FILE, text: `${JSON.stringify(manifest, null, 2)}\n` });
  return { kernel, files, manifest };
}

/**
 * Size findings for the budget rule. A host limit always holds: a surface over it is refused whatever its previous
 * size, and a kernel cap set above it is refused. Any other surface over its cap is refused only when it is larger
 * than at the previous commit (or had no previous size), so shrinking always passes. In rules and agreement mode,
 * raising a surface's cap and growing that surface in the same change is refused, so a raise always lands, and is
 * reviewed, in a commit of its own.
 * @param {Manifest} manifest
 * @param {Manifest | null} previous
 * @param {House["mode"]} mode
 * @returns {{ level: "error" | "info", surface: string, message: string }[]}
 */
export function budgetFindings(manifest, previous, mode) {
  /** @type {{ level: "error" | "info", surface: string, message: string }[]} */
  const out = [];
  for (const [key, size] of Object.entries(manifest.surfaces)) {
    const surface = surfaceOf(key);
    const limit = hostLimit(key);
    const before = previous?.surfaces?.[key];
    const grew = before === undefined || size.chars > before.chars;
    const over = size.chars > size.cap;
    const source = size.cap === BUDGETS[manifest.profile]?.[surface] ? manifest.profile : `[surfaces.${surface}]`;
    if (limit !== null && size.cap > limit) {
      out.push({
        level: "error",
        surface: key,
        message: `${key}: [surfaces.${surface}].cap is ${size.cap}, above ${limit}, the most a host loads (Hermes's kernel prompt section, measured with its framing); the kernel cap never rises above ${limit}`,
      });
    }
    if (limit !== null && size.chars > limit) {
      out.push({ level: "error", surface: key, message: `${key} is ${size.chars} chars, over its hard cap of ${limit}` });
    } else if (over && grew) {
      const was = before === undefined ? "no previous size" : `${before.chars} at the previous commit`;
      out.push({ level: "error", surface: key, message: `${key} is ${size.chars} chars, over its ${source} cap of ${size.cap}, and grew (${was})` });
    } else if (over) {
      out.push({ level: "info", surface: key, message: `${key} is ${size.chars} chars, over its cap of ${size.cap}; it did not grow, so it passes` });
    }
    if (mode !== "none" && before !== undefined && size.cap > before.cap && size.chars > before.chars) {
      out.push({
        level: "error",
        surface: key,
        message: `${key}: its cap rises from ${before.cap} to ${size.cap} in the same change that grows it from ${before.chars} to ${size.chars}; do it in two steps: raise [surfaces.${surface}].cap alone, compile and commit; then grow the text in a later commit`,
      });
    }
    if (size.target !== undefined && size.chars > size.target && !over) {
      out.push({ level: "info", surface: key, message: `${key} is ${size.chars} chars, over its target of ${size.target}` });
    }
  }
  return out;
}
